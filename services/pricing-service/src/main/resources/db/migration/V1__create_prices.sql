-- V1: Pricing baselines per property.
-- Only the *baseline* nightly rate, tax rate, currency, and season tier live in
-- the DB. Weekend, holiday, and loyalty rules are applied at query time by the
-- PriceCalculator service - they're business policy, not state, and we want to
-- tune them without a migration.

CREATE TABLE prices (
    id           UUID            PRIMARY KEY,
    property_id  UUID            NOT NULL UNIQUE,
    base_price   NUMERIC(12, 2)  NOT NULL CHECK (base_price >= 0),
    tax_rate     NUMERIC(5, 4)   NOT NULL CHECK (tax_rate >= 0 AND tax_rate <= 1),
    currency     VARCHAR(3)      NOT NULL,
    season       VARCHAR(16)     NOT NULL CHECK (season IN ('LOW', 'REGULAR', 'HIGH', 'PEAK'))
);

CREATE INDEX idx_prices_property_id ON prices (property_id);

